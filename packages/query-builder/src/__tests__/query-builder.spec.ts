import { createQueryBuilder } from '../index.js';
import {
  AutoGeneratedNumberColumnType,
  DateColumnType,
  LinkColumnType,
  NumberColumnType,
  TaylorDatabase as TaylorDatabaseOriginal,
  TextColumnType,
} from './taylorclient.types.js';

interface OrdersTable {
  id: AutoGeneratedNumberColumnType;
  createdAt: DateColumnType<false>;
  updatedAt: DateColumnType<false>;
  amount: NumberColumnType<false>;
  customer: LinkColumnType<'customers', false>;
}

interface CustomersTable {
  id: AutoGeneratedNumberColumnType;
  createdAt: DateColumnType<false>;
  updatedAt: DateColumnType<false>;
  firstName: TextColumnType<true>;
  lastName: TextColumnType<false>;
  orders: LinkColumnType<'orders', false>;
}

interface TaylorDatabase extends TaylorDatabaseOriginal {
  orders: OrdersTable;
  customers: CustomersTable;
}

describe('QueryBuilder', () => {
  // @ts-ignore
  const qb = createQueryBuilder<TaylorDatabase>({
    baseUrl: 'http://localhost',
    apiKey: 'test',
  });

  it('should compile a select query', () => {
    const { variables } = qb
      .selectFrom('customers')
      .select(['firstName', 'lastName'])
      .where('firstName', '=', 'John')
      .orderBy('lastName', 'asc')
      .paginate(1, 10)
      .compile();

    expect(variables.metadata[0]).toMatchObject({
      type: 'select',
      tableName: 'customers',
      fields: ['firstName', 'lastName'],
      filtersSet: {
        conjunction: 'and',
        filtersSet: [
          {
            field: 'firstName',
            operator: '=',
            value: 'John',
          },
        ],
      },
      sorting: [{ field: 'lastName', direction: 'asc' }],
      pagination: { offset: 0, limit: 10 },
    });
  });

  it('should compile an insert query', () => {
    const { variables } = qb
      .insertInto('customers')
      .values({
        firstName: 'Jane',
        lastName: 'Doe',
      })
      .compile();

    expect(variables.metadata[0]).toMatchObject({
      type: 'create',
      tableName: 'customers',
      createdRecords: [{ firstName: 'Jane', lastName: 'Doe' }],
    });
  });

  it('should compile an update query', () => {
    const { variables } = qb
      .update('customers')
      .set({ lastName: 'Smith' })
      .where('id', '=', 1)
      .compile();

    expect(variables.metadata[0]).toMatchObject({
      type: 'update',
      tableName: 'customers',
      values: { lastName: 'Smith' },
      filtersSet: {
        conjunction: 'and',
        filtersSet: [
          {
            field: 'id',
            operator: '=',
            value: 1,
          },
        ],
      },
    });
  });

  it('should compile a delete query', () => {
    const { variables } = qb
      .deleteFrom('customers')
      .where('id', '=', 1)
      .compile();

    expect(variables.metadata[0]).toMatchObject({
      type: 'delete',
      tableName: 'customers',
      filtersSet: {
        conjunction: 'and',
        filtersSet: [
          {
            field: 'id',
            operator: '=',
            value: 1,
          },
        ],
      },
    });
  });

  it('should compile a batch query', async () => {
    const { variables } = qb
      .batch([
        qb.selectFrom('customers').select(['firstName', 'lastName']),
        qb
          .insertInto('customers')
          .values({ firstName: 'John', lastName: 'Doe' }),
      ])
      .compile();

    expect(variables.metadata).toHaveLength(2);
    expect(variables.metadata[0]).toMatchObject({
      type: 'select',
      tableName: 'customers',
    });
    expect(variables.metadata[1]).toMatchObject({
      type: 'create',
      tableName: 'customers',
    });
  });

  it('should compile an aggregate query', () => {
    const { variables } = qb
      .aggregateFrom('customers')
      .groupBy('firstName', 'asc')
      .withAggregates({
        id: ['sum'],
      })
      .compile();

    expect(variables.metadata[0]).toMatchObject({
      type: 'aggregation',
      tableName: 'customers',
      groupings: [{ field: 'firstName', direction: 'asc' }],
      aggregations: {
        id: ['sum'],
      },
    });
  });

  it('should compile a cross-table query', () => {
    const { variables } = qb
      .selectFrom('customers')
      .where('orders', 'hasAnyOf', qb => qb.where('amount', '>', 100))
      .compile();

    expect(variables.metadata[0]).toMatchObject({
      type: 'select',
      tableName: 'customers',
      filtersSet: {
        conjunction: 'and',
        filtersSet: [
          {
            field: 'orders',
            operator: 'hasAnyOf',
            value: [
              'cross-table',
              {
                conjunction: 'and',
                filtersSet: [
                  {
                    field: 'amount',
                    operator: '>',
                    value: 100,
                  },
                ],
              },
            ],
          },
        ],
      },
    });
  });

  it('should handle a successful transaction', async () => {
    const mockFetch = jest.fn();
    global.fetch = mockFetch;

    const transactionId = 'test-transaction-id';

    // Mock startTransaction
    mockFetch.mockResolvedValueOnce(
      new Response(
        JSON.stringify({ data: { startTransaction: transactionId } }),
      ),
    );
    // Mock execute
    mockFetch.mockResolvedValueOnce(
      new Response(JSON.stringify({ data: { execute: [] } })),
    );
    // Mock commitTransaction
    mockFetch.mockResolvedValueOnce(
      new Response(JSON.stringify({ data: { commitTransaction: true } })),
    );

    await qb.transaction(txQb => {
      return txQb
        .insertInto('customers')
        .values({ firstName: 'John', lastName: 'Doe' })
        .execute();
    });

    expect(mockFetch).toHaveBeenCalledTimes(3);

    // Check startTransaction call
    const startTransactionCall = mockFetch.mock.calls[0];
    expect(JSON.parse(startTransactionCall[1].body).query).toBe(
      'mutation { startTransaction }',
    );

    // Check execute call
    const executeCall = mockFetch.mock.calls[1];
    expect(executeCall[1].headers).toHaveProperty(
      'transaction-id',
      transactionId,
    );
    expect(JSON.parse(executeCall[1].body).variables.metadata[0]).toMatchObject(
      {
        type: 'create',
        tableName: 'customers',
      },
    );

    // Check commitTransaction call
    const commitTransactionCall = mockFetch.mock.calls[2];
    expect(JSON.parse(commitTransactionCall[1].body).query).toBe(
      'mutation { commitTransaction }',
    );
    expect(commitTransactionCall[1].headers).toHaveProperty(
      'transaction-id',
      transactionId,
    );
  });

  it('should handle a failed transaction and rollback', async () => {
    const mockFetch = jest.fn();
    global.fetch = mockFetch;

    const transactionId = 'test-transaction-id-fail';
    const errorMessage = 'Something went wrong';

    // Mock startTransaction
    mockFetch.mockResolvedValueOnce(
      new Response(
        JSON.stringify({ data: { startTransaction: transactionId } }),
      ),
    );
    // Mock execute to throw an error
    mockFetch.mockResolvedValueOnce(
      new Response(JSON.stringify({ errors: [{ message: errorMessage }] })),
    );
    // Mock rollbackTransaction
    mockFetch.mockResolvedValueOnce(
      new Response(JSON.stringify({ data: { rollbackTransaction: true } })),
    );

    await expect(
      qb.transaction(txQb => {
        return txQb
          .insertInto('customers')
          .values({ firstName: 'John', lastName: 'Doe' })
          .execute();
      }),
    ).rejects.toThrow(errorMessage);

    expect(mockFetch).toHaveBeenCalledTimes(3);

    // Check startTransaction call
    const startTransactionCall = mockFetch.mock.calls[0];
    expect(JSON.parse(startTransactionCall[1].body).query).toBe(
      'mutation { startTransaction }',
    );

    // Check execute call
    const executeCall = mockFetch.mock.calls[1];
    expect(executeCall[1].headers).toHaveProperty(
      'transaction-id',
      transactionId,
    );

    // Check rollbackTransaction call
    const rollbackTransactionCall = mockFetch.mock.calls[2];
    expect(JSON.parse(rollbackTransactionCall[1].body).query).toBe(
      'mutation { rollbackTransaction }',
    );
    expect(rollbackTransactionCall[1].headers).toHaveProperty(
      'transaction-id',
      transactionId,
    );
  });

  it('should not have transaction method within a transaction', async () => {
    const mockFetch = jest.fn();
    global.fetch = mockFetch;

    const transactionId = 'test-transaction-id-no-nested';

    // Mock startTransaction and commitTransaction
    mockFetch
      .mockResolvedValueOnce(
        new Response(
          JSON.stringify({ data: { startTransaction: transactionId } }),
        ),
      )
      .mockResolvedValueOnce(
        new Response(JSON.stringify({ data: { commitTransaction: true } })),
      );

    await qb.transaction(async txQb => {
      expect(txQb).not.toHaveProperty('transaction');
    });
  });
});
