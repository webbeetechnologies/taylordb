type ReadonlyColumn<TColumn extends ColumnType<any, any, any, false, any, any>> =
  ColumnType<
    TColumn['raw'],
    never,
    never,
    false,
    TColumn['filters'],
    TColumn['aggregations']
  >;

type InferComputedField<TReturnType extends ComputedReturnType> =
  TReturnType extends 'number'
    ? AutoGeneratedNumberColumnType
    : TReturnType extends 'boolean'
      ? ReadonlyColumn<CheckboxColumnType<false>>
      : TReturnType extends 'date'
        ? AutoGeneratedDateColumnType
        : ReadonlyColumn<TextColumnType<false>>;

export type InferTaylorField<TField extends TaylorFieldDescriptor> =
  TField extends TextFieldDescriptor<infer R, TextLikeFieldType>
    ? TextColumnType<R>
    : TField extends NumberFieldDescriptor<infer R, NumberLikeFieldType>
      ? NumberColumnType<R>
      : TField extends CheckboxFieldDescriptor<infer R>
        ? CheckboxColumnType<R>
        : TField extends DateFieldDescriptor<infer R>
          ? DateColumnType<R>
          : TField extends SearchFieldDescriptor
            ? SearchColumnType<false>
            : TField extends LinkFieldDescriptor<
                  infer TLinkedTo,
                  infer R,
                  'link' | CollaboratorLinkFieldType
                >
              ? LinkColumnType<TLinkedTo, R>
              : TField extends AttachmentFieldDescriptor<infer R>
                ? AttachmentColumnType<R>
                : TField extends SelectFieldDescriptor<
                      infer TOptions,
                      infer R,
                      infer TMode
                    >
                  ? TMode extends 'single'
                    ? SingleSelectColumnType<TOptions, R>
                    : MultiSelectColumnType<TOptions, R>
                  : TField extends AutoNumberFieldDescriptor
                    ? AutoGeneratedNumberColumnType
                    : TField extends AutoDateFieldDescriptor<SystemDateFieldType>
                      ? AutoGeneratedDateColumnType
                      : TField extends ComputedFieldDescriptor<
                            ComputedFieldType,
                            infer TReturnType
                          >
                        ? InferComputedField<TReturnType>
                        : never;

export type InferTaylorTable<TTableSchema extends TaylorTableSchema> = {
  [K in keyof TTableSchema]: InferTaylorField<TTableSchema[K]>;
};

export type InferTaylorDatabase<TSchema extends TaylorRuntimeSchema> = {
  [K in keyof TSchema]: InferTaylorTable<TSchema[K]>;
};
