type RequiredOption<R extends boolean = boolean> = {
  required: R;
};

type ComputedReturnType = 'string' | 'json' | 'select' | 'number' | 'boolean' | 'date';

type BaseFieldDescriptor<
  TType extends string,
  R extends boolean,
  TInsertable extends boolean,
  TUpdatable extends boolean,
> = {
  type: TType;
  required: R;
  insertable: TInsertable;
  updatable: TUpdatable;
};

